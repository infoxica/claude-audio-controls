import { test, expect } from '@playwright/test';
import { readFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, extname } from 'node:path';
test('settings and popup render with Claude branding and no unavailable review links', async ({ page }) => {
  const base = resolve('dist');
  await page.route('http://127.0.0.1:4173/**', route => {
    const file = resolve(base, '.' + new URL(route.request().url()).pathname);
    if (!file.startsWith(base + '\\') && !file.startsWith(base + '/')) return route.abort();
    if (!existsSync(file)) return route.fulfill({ status: 404, body: 'Not found' });
    return route.fulfill({ body: readFileSync(file), contentType: ({'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css','.png':'image/png'})[extname(file)] || 'application/octet-stream' });
  });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.goto('http://127.0.0.1:4173/src/options/index.html');
  await expect(page.getByRole('heading', { name: 'Audio & Playback Preferences' })).toBeVisible();
  expect(await page.locator('a[href=""]').count()).toBe(0);
  mkdirSync('assets/demo', { recursive: true });
  await expect(page.locator('#options-language button')).toHaveCount(68);
  expect(await page.locator('.dashboard-layout').evaluate(el=>el.getBoundingClientRect().width)).toBe(1280);
  await expect(page.getByRole('combobox', { name: /Playback Speed/i })).toBeInViewport();
  await page.screenshot({ path: 'assets/demo/settings.png', animations: 'disabled' });
  await page.getByRole('radio', { name: 'Light', exact: true }).check();
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(250, 249, 245)');
  const contrast = await page.locator('.language-choice[aria-pressed=true] .language-hint').evaluate(el => {
    const luminance = color => { const values=color.match(/[\d.]+/g).slice(0,3).map(Number).map(c=>{c/=255;return c<=.04045?c/12.92:((c+.055)/1.055)**2.4;});return .2126*values[0]+.7152*values[1]+.0722*values[2]; };
    const text=luminance(getComputedStyle(el).color), bg=luminance(getComputedStyle(document.querySelector('.dashboard-main')).backgroundColor);
    return (Math.max(text,bg)+.05)/(Math.min(text,bg)+.05);
  });
  expect(contrast).toBeGreaterThanOrEqual(4.5);
  await expect(page.locator('.theme-selector')).toHaveCSS('background-color','rgba(0, 0, 0, 0.05)');
  await page.screenshot({ path: 'assets/demo/settings-light.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('radio', { name: 'Dark', exact: true }).check();
  await page.setViewportSize({ width: 360, height: 660 });
  await page.goto('http://127.0.0.1:4173/src/popup/index.html');
  await expect(page.getByText('Default Playback Speed', { exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: /Playback Speed/i })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'assets/demo/popup.png', animations: 'disabled' });
  await page.getByRole('radio', { name: 'Light', exact: true }).check();
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(250, 249, 245)');
  await page.screenshot({ path: 'assets/demo/popup-light.png', animations: 'disabled' });
  await expect(page.getByRole('link', {name:'Feature tour',exact:true})).toHaveCount(0);
  await page.getByRole('button', {name:'About',exact:true}).click();
  const tour = page.getByRole('link', {name:'Feature tour',exact:true});
  await expect(tour).toBeVisible();
  await expect(tour).toHaveAttribute('href','../tour/index.html');
  await expect(tour).toHaveCSS('border-radius','12px');
  await page.screenshot({path:'build/popup-about-tour.png',animations:'disabled'});
  await page.getByRole('radio', {name:'Dark',exact:true}).check();
  await expect(page.locator('body')).toHaveCSS('background-color','rgb(38, 38, 36)');
  expect(await page.locator('.about-brand').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:'build/popup-about-dark.png',animations:'disabled'});
  await page.locator('.quick-start summary').click();
  await expect(page.locator('.quick-start details')).toHaveAttribute('open','');
  await page.evaluate(()=>{window.chrome={commands:{getAll:async()=>[]}};});
  await page.getByRole('button',{name:'Keys',exact:true}).click();
  const rows = await page.locator('.command-shortcuts .shortcut-row').evaluateAll(els=>els.map(el=>{const r=el.getBoundingClientRect();return {top:r.top,bottom:r.bottom,width:r.width};}));
  expect(rows.length).toBeGreaterThan(10);
  for(let i=1;i<rows.length;i++) expect(rows[i].top).toBeGreaterThanOrEqual(rows[i-1].bottom);
  expect(Math.min(...rows.map(r=>r.width))).toBeGreaterThan(280);
  await page.screenshot({path:'build/popup-keys-fixed.png',animations:'disabled'});
});

